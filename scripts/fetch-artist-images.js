#!/usr/bin/env node
/*
  Fetch artist picture URLs from Spotify for every roster and snapshot artist and write them to data/artist-media.js.
  The site stores no image files: browsers load the pictures from Spotify's image host (https://i.scdn.co) at view time.

  Run it on the owner's own computer (Node 18 or newer). The client secret must never be put into the site or committed.

    SPOTIFY_CLIENT_ID=... SPOTIFY_CLIENT_SECRET=... node scripts/fetch-artist-images.js [--refresh]

  - Credentials come from a Spotify developer app (Client Credentials flow, no user login).
  - Matching is strict: a search result is used only when its name equals the artist name (case and accents ignored).
    Everything else is listed in scripts/artist-images-review.txt and gets no picture (the site shows an initials monogram).
  - Exact matches by Spotify artist ID: put a JSON object { "Artist name": "spotifyArtistId" } into scripts/spotify-ids.json
    (optional). Names listed there skip the search.
  - Names already present in data/artist-media.js are skipped unless --refresh is given. Progress is saved every 25 artists.
*/
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'data', 'artist-media.js');
const REVIEW = path.join(__dirname, 'artist-images-review.txt');
const IDS_FILE = path.join(__dirname, 'spotify-ids.json');
const IMAGE_HOST = 'i.scdn.co';

const norm = (t) => String(t).toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '').trim();
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

function loadWindowFile(file) {
  const saved = global.window;
  global.window = {};
  try {
    delete require.cache[require.resolve(file)];
    require(file);
    return global.window;
  } finally {
    global.window = saved;
  }
}

function collectNames() {
  const data = loadWindowFile(path.join(ROOT, 'data', 'snapshots.js')).LEDGERTONE || {};
  const banned = new Set((data.banned || []).map((n) => norm(n)));
  const seen = new Map();
  const add = (n) => {
    const name = String(n || '').trim();
    const k = norm(name);
    if (name && !banned.has(k) && !seen.has(k)) seen.set(k, name);
  };
  (data.genres || []).forEach((g) => (g.roster || []).forEach(add));
  (data.snapshots || []).forEach((s) => (s.artists || []).forEach((a) => add(a && a.name)));
  return [...seen.values()];
}

function loadMedia() {
  if (!fs.existsSync(OUT)) return {};
  const m = loadWindowFile(OUT).LEDGERTONE_MEDIA;
  return m && typeof m === 'object' ? Object.assign({}, m) : {};
}

function saveMedia(media) {
  const keys = Object.keys(media).sort();
  const body = keys.map((k) => '  ' + JSON.stringify(k) + ': ' + JSON.stringify(media[k])).join(',\n');
  const text = '/*\n  Generated by scripts/fetch-artist-images.js. Do not edit by hand.\n' +
    '  Artist picture URLs only (Spotify image host), keyed by the lowercase, accent-free artist name. No image files are stored in the repository.\n' +
    '*/\nwindow.LEDGERTONE_MEDIA = {' + (body ? '\n' + body + '\n' : '') + '};\n';
  fs.writeFileSync(OUT, text.replace(/\n/g, '\r\n'));
}

// the smallest picture that is at least 100 px wide (the list shows 36 px, this keeps retina sharp), else the largest
function pickImage(images) {
  const list = (images || []).filter((i) => i && typeof i.url === 'string');
  if (!list.length) return null;
  const wide = list.filter((i) => Number(i.width) >= 100).sort((a, b) => a.width - b.width);
  if (wide.length) return wide[0].url;
  return list.slice().sort((a, b) => (b.width || 0) - (a.width || 0))[0].url;
}

function makeClient(id, secret) {
  let token = null;
  let expires = 0;
  async function auth() {
    const res = await fetch('https://accounts.spotify.com/api/token', {
      method: 'POST',
      headers: {
        Authorization: 'Basic ' + Buffer.from(id + ':' + secret).toString('base64'),
        'Content-Type': 'application/x-www-form-urlencoded',
      },
      body: 'grant_type=client_credentials',
    });
    if (!res.ok) throw new Error('Token request failed: HTTP ' + res.status + ' (check the client ID and secret)');
    const j = await res.json();
    token = j.access_token;
    expires = Date.now() + (Number(j.expires_in) || 3600) * 1000 - 60000;
  }
  async function get(url) {
    for (let attempt = 0; attempt < 6; attempt++) {
      if (!token || Date.now() > expires) await auth();
      const res = await fetch(url, { headers: { Authorization: 'Bearer ' + token } });
      if (res.status === 401) { token = null; continue; }
      if (res.status === 429) {
        const wait = Math.min(Number(res.headers.get('retry-after')) || 5, 120);
        console.log('  rate limited, waiting ' + wait + ' s');
        await sleep((wait + 1) * 1000);
        continue;
      }
      if (res.status === 404) return null;
      if (!res.ok) throw new Error('HTTP ' + res.status + ' for ' + url);
      return res.json();
    }
    throw new Error('Too many retries for ' + url);
  }
  return { get };
}

async function findArtist(client, name) {
  const base = 'https://api.spotify.com/v1/search?type=artist&limit=5&q=';
  const queries = ['artist:"' + name.replace(/"/g, '') + '"', name];
  let candidates = [];
  for (const q of queries) {
    const j = await client.get(base + encodeURIComponent(q));
    const items = (j && j.artists && j.artists.items) || [];
    candidates = candidates.concat(items.map((i) => i.name));
    const exact = items.filter((i) => i && norm(i.name) === norm(name));
    if (exact.length) {
      exact.sort((a, b) => (Number(b.popularity) || 0) - (Number(a.popularity) || 0));
      return { artist: exact[0], candidates };
    }
    await sleep(150);
  }
  return { artist: null, candidates };
}

async function main() {
  const id = process.env.SPOTIFY_CLIENT_ID;
  const secret = process.env.SPOTIFY_CLIENT_SECRET;
  if (!id || !secret) {
    console.error('Set SPOTIFY_CLIENT_ID and SPOTIFY_CLIENT_SECRET (Spotify developer dashboard, Client Credentials).');
    process.exit(1);
  }
  const refresh = process.argv.includes('--refresh');
  const ids = fs.existsSync(IDS_FILE) ? JSON.parse(fs.readFileSync(IDS_FILE, 'utf8')) : {};
  const idByName = new Map(Object.entries(ids).map(([n, v]) => [norm(n), String(v)]));
  const names = collectNames();
  const media = loadMedia();
  const review = [];
  const client = makeClient(id, secret);
  let done = 0, added = 0;

  for (const name of names) {
    const key = norm(name);
    if (media[key] && !refresh) continue;
    let artist = null;
    let candidates = [];
    try {
      if (idByName.has(key)) {
        artist = await client.get('https://api.spotify.com/v1/artists/' + encodeURIComponent(idByName.get(key)));
        if (!artist) review.push(name + ' | the ID in spotify-ids.json was not found');
      } else {
        ({ artist, candidates } = await findArtist(client, name));
        if (!artist) review.push(name + ' | no exact name match' + (candidates.length ? ' | candidates: ' + [...new Set(candidates)].join(', ') : ' | no results'));
      }
    } catch (e) {
      review.push(name + ' | error: ' + e.message);
      continue;
    }
    if (artist) {
      const url = pickImage(artist.images);
      let host = '';
      try { host = new URL(url).hostname; } catch (e) { /* no url */ }
      if (!url) review.push(name + ' | matched on Spotify but the artist has no picture');
      else if (host !== IMAGE_HOST) review.push(name + ' | unexpected image host ' + host + ', not used');
      else { media[key] = url; added++; }
    }
    if (++done % 25 === 0) { saveMedia(media); console.log(done + ' artists processed, ' + added + ' pictures found'); }
    await sleep(150);
  }

  saveMedia(media);
  fs.writeFileSync(REVIEW, review.length ? review.join('\n') + '\n' : 'Nothing to review.\n');
  console.log('Done. ' + Object.keys(media).length + ' pictures in data/artist-media.js, ' + review.length + ' names need a look (scripts/artist-images-review.txt).');
}

if (require.main === module) main().catch((e) => { console.error(e.message); process.exit(1); });
module.exports = { norm, pickImage };
